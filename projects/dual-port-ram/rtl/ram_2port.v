`timescale 1ns/1ps
`default_nettype none

// =============================================================================
// Module      : ram_2port
// Description : True dual-port synchronous RAM with registered read outputs
//               and an active-high asynchronous reset for the output registers.
//
// Default organization
//   - Word width : 8 bits
//   - Address    : 4 bits
//   - Depth      : 2^4 = 16 words
//
// Functional convention
//   - Both ports use the same rising-edge clock.
//   - Each port has an independent write enable and read enable.
//   - Read data is registered. When re_a/re_b is low, the corresponding output
//     retains its previous value.
//   - A read and a write to the same address on the same clock edge implement
//     READ_FIRST behavior: the read output receives the old word, while the new
//     word is stored after the edge.
//   - Simultaneous writes by A and B to the same address are illegal. The
//     testbench detects this prohibited stimulus.
//   - Reset r clears only rdata_a and rdata_b. The memory array is intentionally
//     not reset because bulk-resetting an SRAM array is generally not a
//     memory-inference-friendly hardware structure.
// =============================================================================

module ram_2port #(
    parameter integer DATA_WIDTH = 8,
    parameter integer ADDR_WIDTH = 4
) (
    input  wire                  clk,
    input  wire                  r,

    input  wire                  we_a,
    input  wire                  re_a,
    input  wire [ADDR_WIDTH-1:0] addr_a,
    input  wire [DATA_WIDTH-1:0] wdata_a,
    output reg  [DATA_WIDTH-1:0] rdata_a,

    input  wire                  we_b,
    input  wire                  re_b,
    input  wire [ADDR_WIDTH-1:0] addr_b,
    input  wire [DATA_WIDTH-1:0] wdata_b,
    output reg  [DATA_WIDTH-1:0] rdata_b
);

    localparam integer DEPTH = (1 << ADDR_WIDTH);

    reg [DATA_WIDTH-1:0] mem [0:DEPTH-1];

    // A single sequential process owns the memory array. Nonblocking
    // assignments preserve the intended READ_FIRST behavior.
    always @(posedge clk or posedge r) begin
        if (r) begin
            rdata_a <= {DATA_WIDTH{1'b0}};
            rdata_b <= {DATA_WIDTH{1'b0}};
        end
        else begin
            // Synchronous registered reads.
            if (re_a) begin
                rdata_a <= mem[addr_a];
            end

            if (re_b) begin
                rdata_b <= mem[addr_b];
            end

            // Independent writes. Same-address dual writes are prohibited by
            // the interface contract and are never generated by the testbench.
            if (we_a) begin
                mem[addr_a] <= wdata_a;
            end

            if (we_b) begin
                mem[addr_b] <= wdata_b;
            end
        end
    end

endmodule

`default_nettype wire
